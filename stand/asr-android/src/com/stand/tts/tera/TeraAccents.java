    /** Пословно проставляет '+' по лексикону, затем по частотному словарю (dict,
     *  может быть null); регистр и пунктуация сохраняются. */
    static String accentize(String text, RuAccentDict dict) {
        if (text == null || text.isEmpty()) return text;
        StringBuilder out = new StringBuilder(text.length() + 16);
        int i = 0, n = text.length();
        while (i < n) {
            char c = text.charAt(i);
            if (isCyr(c) || c == '+') {
                int j = i;                                  // '+' is part of the word (stress marker)
                while (j < n && (isCyr(text.charAt(j)) || text.charAt(j) == '+')) j++;
                String w = text.substring(i, j);
                // A word already carrying a '+' (e.g. the backend's RUAccent-marked answer) is kept
                // verbatim — deliberate stress. Only UNMARKED words get the on-device dictionary
                // stress, so a partially-marked answer still gets every word stressed.
                out.append(w.indexOf('+') >= 0 ? w : mapWord(w, dict));
                i = j;
            } else {
                out.append(c);
                i++;
            }
        }
        return out.toString();
    }

    private static boolean isCyr(char c) {
        return (c >= '\u0400' && c <= '\u04FF') || c == '\u0451' || c == '\u0401';
    }

    private static String mapWord(String word, RuAccentDict dict) {
        String key = word.toLowerCase();
        String marked = LEX.get(key);                 // вшитый лексикон — приоритет
        if (marked == null && dict != null) {
            marked = dict.lookup(key);                // частотный словарь — fallback
        }
        if (marked == null) return word;              // нигде нет — как есть
        if (Character.isUpperCase(word.charAt(0))) {  // вернуть заглавную первой буквы
            return Character.toUpperCase(marked.charAt(0)) + marked.substring(1);
        }
        return marked;
    }
